package controlstm.looping;

public class DoWhileLoop {
public static void main(String[] args) {
	/*
	 * --------------Do while-------------------
	 * # synatx:
	 * 
	 * 	do{
	 * 		//statements
	 * 		
	 * 	i++;
	 * 	}while(condition);
	 */
	int i = 200;
	do {
		System.out.println("Min. 1 chotii vitra janxa");
		i++;
	}while(i<10);
	
	
}
}
